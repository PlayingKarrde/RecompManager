"""A fake GitHub for tests: API from recorded fixtures, plus in-memory release assets.

Never serves real game data. Asset bodies are generated bytes.
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import re
from pathlib import Path
from typing import Any

import httpx

FIXTURES = Path(__file__).parent / "fixtures" / "github"


class FlakyStream(httpx.AsyncByteStream):
    """Sends ``cut`` bytes, then drops the connection."""

    def __init__(self, data: bytes, cut: int) -> None:
        self.data, self.cut = data, cut

    async def __aiter__(self):
        yield self.data[: self.cut]
        raise httpx.ReadError("connection reset")


class SlowStream(httpx.AsyncByteStream):
    def __init__(self, data: bytes, chunk: int = 1024, delay: float = 0.05) -> None:
        self.data, self.chunk, self.delay = data, chunk, delay

    async def __aiter__(self):
        for i in range(0, len(self.data), self.chunk):
            await asyncio.sleep(self.delay)
            yield self.data[i : i + self.chunk]


class FakeGitHub:
    def __init__(self) -> None:
        self.repos: dict[str, dict[str, Any]] = {}  # lowercase owner/name → {repo, releases}
        self.etags: dict[str, int] = {}  # bumped when a repo's releases change
        self.blobs: dict[str, bytes] = {}  # download URL → bytes
        self.requests: list[httpx.Request] = []
        self.flaky: dict[str, int] = {}  # URL → cut point for the next request only
        self.slow: set[str] = set()

    # ---------------------------------------------------------------- setup

    def load_fixture(self, name: str) -> None:
        data = json.loads((FIXTURES / name).read_text(encoding="utf-8"))
        key = data["repo"]["full_name"].lower()
        self.repos[key] = data
        self.etags[key] = 1

    def load_all_fixtures(self) -> None:
        for p in sorted(FIXTURES.glob("*.json")):
            self.load_fixture(p.name)

    def add_repo(self, full_name: str, description: str = "") -> None:
        self.repos[full_name.lower()] = {
            "repo": {
                "full_name": full_name,
                "name": full_name.split("/")[1],
                "description": description,
            },
            "releases": [],
        }
        self.etags[full_name.lower()] = 1

    def publish(
        self,
        full_name: str,
        tag: str,
        assets: dict[str, bytes],
        *,
        prerelease: bool = False,
        published_at: str | None = None,
        digest: bool = True,
        bad_digest_for: str | None = None,
    ) -> dict[str, Any]:
        """Add a release with in-memory assets; newest first like GitHub."""
        key = full_name.lower()
        rel_list = self.repos[key]["releases"]
        n = len(rel_list) + 1
        rel = {
            "id": n,
            "tag_name": tag,
            "name": f"Release {tag}",
            "draft": False,
            "prerelease": prerelease,
            "published_at": published_at or f"2026-10-{n:02d}T12:00:00Z",
            "html_url": f"https://github.com/{full_name}/releases/tag/{tag}",
            "body": f"Notes for {tag}",
            "assets": [],
        }
        for i, (name, body) in enumerate(assets.items()):
            url = f"https://github.com/{full_name}/releases/download/{tag}/{name}"
            self.blobs[url] = body
            sha = hashlib.sha256(body).hexdigest()
            if name == bad_digest_for:
                sha = "0" * 64
            rel["assets"].append(
                {
                    "id": n * 100 + i,
                    "name": name,
                    "size": len(body),
                    "digest": f"sha256:{sha}" if digest else None,
                    "content_type": "application/octet-stream",
                    "browser_download_url": url,
                }
            )
        rel_list.insert(0, rel)
        self.etags[key] += 1
        return rel

    # ---------------------------------------------------------------- transport

    def transport(self) -> httpx.MockTransport:
        return httpx.MockTransport(self.handle)

    def api_requests(self, path_suffix: str) -> list[httpx.Request]:
        return [r for r in self.requests if r.url.path.endswith(path_suffix)]

    def handle(self, request: httpx.Request) -> httpx.Response:
        self.requests.append(request)
        url = str(request.url)
        if request.url.host == "api.github.com":
            return self._api(request)
        if url in self.blobs:
            return self._blob(request, url)
        return httpx.Response(404)

    def _api(self, request: httpx.Request) -> httpx.Response:
        m = re.match(r"^/repos/([^/]+/[^/]+)(/releases)?$", request.url.path)
        if not m or m.group(1).lower() not in self.repos:
            return httpx.Response(404, json={"message": "Not Found"})
        key = m.group(1).lower()
        data = self.repos[key]
        if not m.group(2):
            return httpx.Response(200, json=data["repo"])
        etag = f'"rel-{key}-{self.etags[key]}"'
        if request.headers.get("if-none-match") == etag:
            return httpx.Response(304, headers={"etag": etag})
        return httpx.Response(200, json=data["releases"], headers={"etag": etag})

    def _blob(self, request: httpx.Request, url: str) -> httpx.Response:
        body = self.blobs[url]
        start = 0
        if rng := request.headers.get("range"):
            m = re.match(r"bytes=(\d+)-$", rng)
            assert m, rng
            start = int(m.group(1))
            if start >= len(body):
                return httpx.Response(416)
        part = body[start:]
        status = 206 if start else 200
        headers = {"content-length": str(len(part))}
        if url in self.flaky:
            cut = self.flaky.pop(url)
            return httpx.Response(status, headers=headers, stream=FlakyStream(part, cut))
        if url in self.slow:
            return httpx.Response(status, headers=headers, stream=SlowStream(part))
        return httpx.Response(status, headers=headers, content=part)
